def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"

def row(table, *vals):
    return "INSERT INTO `%s` VALUES (%s);" % (table, ", ".join(q(v) for v in vals))

